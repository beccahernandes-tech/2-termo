---CORREÇÃO SOMATIVA 01 - OFICINA REBECCA

CREATE DATABASE IF NOT EXISTS OFICINA_REBECCA;

USE OFICINA_REBECCA;

CREATE TABLE IF NOT EXISTS CLIENTES(
    ID_CLIENTES INT AUTO_INCREMENT PRIMARY KEY,
    NOME varchar(60) not null,
    CPF varchar(14) not null unique,
    EMAIL varchar(50),
    TELEFONE varchar(14),
    endereço varchar(20),
    status_cliente ENUM('ATIVO', 'DESATIVADO') DEFAULT `ATIVO`

);

CREATE TABLE IF NOT EXISTS VEICULOS (
    ID_VEICULOS INT AUTO_INCREMENT PRIMARY KEY,
    PLACA CHAR(8) NOT NULL UNIQUE,
    TIPO enum ("CARRO", "CAMINHONETE", "MOTO") default 'CARRO',
    COR VARCHAR(20),
    QUILOMETRAGEM FLOAT,
    TIPO_MOTOR ENUM ('ELÉTRICO', 'COMBUSTÃO'),
    DATA_CADASTRO TIMESTAMP DEFAULT
    CURRENT_TIMESTAMP
);

create table IF NOT EXISTS MARCA (
id_marca int auto_increment primary key,
ano_LANÇAMENTO year,
NOME varchar(30) not null,
PAIS varchar(50),
SITE_MARCA VARCHAR(100),
STATUS_MARCA ENUM,
DATA_CADASTRO TIMESTAMP DEFAULT
CURRENT_TIMESTAMP
);


